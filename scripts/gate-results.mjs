// Records the real results of the three gated checks into src/data/gateResults.ts, which the
// Failure Tests screen reads. Usage: node scripts/gate-results.mjs [--skip-acceptance]
// Run it before a build so the screen shows the gates for the code being shipped.
import { execSync, spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';

const skipAcceptance = process.argv.includes('--skip-acceptance');
const sh = cmd => execSync(cmd, { encoding: 'utf8' }).trim();
const run = (cmd, args) => spawnSync(cmd, args, { encoding: 'utf8', shell: process.platform === 'win32', maxBuffer: 64 * 1024 * 1024 });
const tmp = mkdtempSync(join(tmpdir(), 'orbit-gates-'));

// Gate 1: lint
console.log('Gate 1: lint');
const lintOut = join(tmp, 'lint.json');
run('npx', ['eslint', '.', '-f', 'json', '-o', lintOut]);
const lintFiles = JSON.parse(readFileSync(lintOut, 'utf8'));
const lint = {
  errors: lintFiles.reduce((n, f) => n + f.errorCount, 0),
  warnings: lintFiles.reduce((n, f) => n + f.warningCount, 0),
  files: lintFiles.length
};
lint.state = lint.errors === 0 ? 'passed' : 'failed';

// Gate 2: unit
console.log('Gate 2: unit tests');
const unitOut = join(tmp, 'unit.json');
run('npx', ['vitest', 'run', '--reporter=json', `--outputFile=${unitOut}`]);
const unitJson = JSON.parse(readFileSync(unitOut, 'utf8'));
const unit = {
  passed: unitJson.numPassedTests,
  failed: unitJson.numFailedTests,
  total: unitJson.numTotalTests,
  files: unitJson.testResults
    .map(t => ({
      file: relative(process.cwd(), t.name).replace(/\\/g, '/'),
      passed: t.assertionResults.filter(a => a.status === 'passed').length,
      failed: t.assertionResults.filter(a => a.status === 'failed').length
    }))
    .sort((a, b) => a.file.localeCompare(b.file))
};
unit.state = unit.failed === 0 && unit.total > 0 ? 'passed' : 'failed';

// Gate 3: acceptance
let acceptance = { state: 'not-run', passed: 0, failed: 0, total: 0 };
if (!skipAcceptance) {
  console.log('Gate 3: acceptance tests');
  const res = run('npx', ['playwright', 'test', '--reporter=json']);
  try {
    const stats = JSON.parse(res.stdout.slice(res.stdout.indexOf('{'))).stats;
    const failed = stats.unexpected + stats.flaky;
    acceptance = { state: failed === 0 && stats.expected > 0 ? 'passed' : 'failed', passed: stats.expected, failed, total: stats.expected + failed };
  } catch {
    console.log('  Acceptance output could not be read; recorded as not run.');
  }
}

const results = {
  recordedAt: new Date().toISOString(),
  branch: sh('git rev-parse --abbrev-ref HEAD'),
  commit: sh('git rev-parse --short HEAD'),
  lint: { state: lint.state, errors: lint.errors, warnings: lint.warnings, files: lint.files },
  unit: { state: unit.state, passed: unit.passed, failed: unit.failed, total: unit.total, files: unit.files },
  acceptance
};

writeFileSync(
  'src/data/gateResults.ts',
  `// Generated by scripts/gate-results.mjs from real tool output. Do not edit by hand.\n` +
    `import type { GateResults } from '../lib/gates';\n\n` +
    `export const GATE_RESULTS: GateResults = ${JSON.stringify(results, null, 2)};\n`
);
console.log(`Recorded: lint ${lint.state}, unit ${unit.passed}/${unit.total}, acceptance ${acceptance.state} ${acceptance.passed}/${acceptance.total}`);
process.exit(lint.state === 'passed' && unit.state === 'passed' && acceptance.state !== 'failed' ? 0 : 1);
